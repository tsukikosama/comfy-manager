CREATE TABLE IF NOT EXISTS `comfy_task` (
    `id`                  bigint        NOT NULL AUTO_INCREMENT          COMMENT 'ID',
    `user_id`             bigint        NOT NULL                         COMMENT '用户ID',
    `schedule_id`         bigint        DEFAULT NULL                     COMMENT '来源计划ID',
    `task_batch_id`       bigint        NOT NULL                         COMMENT '所属批次ID',
    `instance_id`         bigint        NOT NULL                         COMMENT '目标实例ID',
    `workflow_id`         bigint        NOT NULL                         COMMENT '来源工作流ID',
    `item_index`          int           NOT NULL DEFAULT 1              COMMENT '任务项序号（从1开始）',
    `scheduled_at_utc`    datetime(3)   DEFAULT NULL                     COMMENT '计划触发时间（UTC）',
    `actual_params_json`  longtext       DEFAULT NULL                    COMMENT '展开的实际参数、种子及素材引用',
    `final_prompt_json`   longtext       DEFAULT NULL                    COMMENT '冻结的最终 prompt',
    `endpoint_url`        varchar(512)  DEFAULT NULL                     COMMENT '原目标地址（从快照，不随实例变更改变）',
    `target_device_uuid`  varchar(64)   DEFAULT NULL                     COMMENT '原目标设备UUID',
    `status`              tinyint       UNSIGNED NOT NULL DEFAULT 1     COMMENT '任务状态',
    `version_no`          bigint        NOT NULL DEFAULT 0              COMMENT '乐观锁版本号',
    `current_attempt_no`  int           NOT NULL DEFAULT 0              COMMENT '当前尝试号（未执行为0）',
    `claim_token`         varchar(64)   DEFAULT NULL                     COMMENT '领取令牌',
    `claim_page_uuid`     varchar(64)   DEFAULT NULL                     COMMENT '领取页UUID',
    `claim_device_uuid`   varchar(64)   DEFAULT NULL                     COMMENT '领取设备UUID',
    `claim_epoch`         bigint        DEFAULT NULL                     COMMENT '领取时租约epoch',
    `claimed_at`          datetime(3)   DEFAULT NULL                     COMMENT '领取时间（UTC）',
    `submitted_at`        datetime(3)   DEFAULT NULL                     COMMENT '提交时间（UTC）',
    `prompt_id`           varchar(64)   DEFAULT NULL                     COMMENT 'ComfyUI promptId',
    `finished_at`         datetime(3)   DEFAULT NULL                     COMMENT '完成时间（UTC）',
    `create_user`         bigint        DEFAULT NULL                    COMMENT '创建人',
    `create_time`         datetime      NOT NULL                        COMMENT '创建时间',
    `update_user`         bigint        DEFAULT NULL                    COMMENT '修改人',
    `update_time`         datetime      DEFAULT NULL                    COMMENT '修改时间',
    `deleted`             bigint        NOT NULL DEFAULT 0              COMMENT '是否已删除（0：否；id：是）',
    PRIMARY KEY (`id`),
    UNIQUE INDEX `uk_comfy_task_batch_item`(`task_batch_id`, `item_index`),
    INDEX `idx_comfy_task_user_status`(`user_id`, `status`),
    INDEX `idx_comfy_task_batch_status`(`task_batch_id`, `status`),
    INDEX `idx_comfy_task_status_scheduled`(`status`, `scheduled_at_utc`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='ComfyUI 任务表';

