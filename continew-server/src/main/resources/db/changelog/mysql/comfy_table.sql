CREATE TABLE IF NOT EXISTS `comfy_instance` (
    `id`                  bigint        NOT NULL AUTO_INCREMENT          COMMENT 'ID',
    `user_id`             bigint        NOT NULL                         COMMENT '用户ID',
    `name`                varchar(100)  NOT NULL                         COMMENT '实例名称',
    `endpoint_url`        varchar(512)  NOT NULL                         COMMENT 'ComfyUI 地址（HTTP/HTTPS）',
    `endpoint_hash`       char(64)      NOT NULL                         COMMENT '地址哈希（SHA-256 十六进制文本）',
    `device_uuid`         varchar(64)   NOT NULL                         COMMENT '设备UUID（站点存储随机标识，非硬件身份）',
    `config_revision`     bigint        NOT NULL DEFAULT 0              COMMENT '地址或设备变化时的配置版本（递增）',
    `page_uuid`           varchar(64)   DEFAULT NULL                    COMMENT '当前执行页UUID（启用本页执行后写入）',
    `login_token_digest`  binary(32)     DEFAULT NULL                    COMMENT '登录令牌摘要（SHA-256 原始字节）',
    `lease_epoch`         bigint        NOT NULL DEFAULT 0              COMMENT '执行租约递增 epoch',
    `lease_status`        tinyint       UNSIGNED NOT NULL DEFAULT 2     COMMENT '执行租约状态（1：在线/ACTIVE；2：离线/OFFLINE）',
    `lease_expires_at`    datetime(3)   DEFAULT NULL                    COMMENT '租约到期时间（UTC）',
    `last_heartbeat_at`   datetime(3)   DEFAULT NULL                    COMMENT '最后心跳时间（UTC）',
    `status`              tinyint       UNSIGNED NOT NULL DEFAULT 1     COMMENT '实例状态（1：启用；2：禁用）',
    `create_user`         bigint        DEFAULT NULL                    COMMENT '创建人',
    `create_time`         datetime      NOT NULL                        COMMENT '创建时间',
    `update_user`         bigint        DEFAULT NULL                    COMMENT '修改人',
    `update_time`         datetime      DEFAULT NULL                    COMMENT '修改时间',
    `deleted`             bigint        NOT NULL DEFAULT 0              COMMENT '是否已删除（0：否；id：是）',
    PRIMARY KEY (`id`),
    UNIQUE INDEX `uk_comfy_instance_user_endpoint`(`user_id`, `endpoint_hash`),
    INDEX `idx_comfy_instance_user_lease`(`user_id`, `lease_status`),
    INDEX `idx_comfy_instance_device`(`device_uuid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='ComfyUI 实例表';

CREATE TABLE IF NOT EXISTS `comfy_workflow` (
    `id`                  bigint        NOT NULL AUTO_INCREMENT          COMMENT 'ID',
    `user_id`             bigint        NOT NULL                         COMMENT '用户ID',
    `name`                varchar(100)  NOT NULL                         COMMENT '工作流名称',
    `description`         varchar(255)  DEFAULT NULL                     COMMENT '描述',
    `raw_workflow_json`   longtext       DEFAULT NULL                    COMMENT '普通 UI workflow JSON',
    `api_prompt_json`     longtext       NOT NULL                        COMMENT 'API prompt JSON（执行格式）',
    `node_bindings_json`  longtext       DEFAULT NULL                    COMMENT '参数绑定（nodeId/classType/inputName/类型）',
    `config_revision`     bigint        NOT NULL DEFAULT 0              COMMENT '工作流配置版本（递增）',
    `status`              tinyint       UNSIGNED NOT NULL DEFAULT 1     COMMENT '状态（1：草稿；2：就绪）',
    `create_user`         bigint        DEFAULT NULL                    COMMENT '创建人',
    `create_time`         datetime      NOT NULL                        COMMENT '创建时间',
    `update_user`         bigint        DEFAULT NULL                    COMMENT '修改人',
    `update_time`         datetime      DEFAULT NULL                    COMMENT '修改时间',
    `deleted`             bigint        NOT NULL DEFAULT 0              COMMENT '是否已删除（0：否；id：是）',
    PRIMARY KEY (`id`),
    INDEX `idx_comfy_workflow_user`(`user_id`),
    INDEX `idx_comfy_workflow_status`(`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='ComfyUI 工作流表';

CREATE TABLE IF NOT EXISTS `comfy_schedule` (
    `id`                    bigint        NOT NULL AUTO_INCREMENT          COMMENT 'ID',
    `user_id`               bigint        NOT NULL                         COMMENT '用户ID',
    `name`                  varchar(100)  NOT NULL                         COMMENT '计划名称',
    `instance_id`           bigint        NOT NULL                         COMMENT '固定目标实例ID',
    `workflow_id`           bigint        NOT NULL                         COMMENT '来源工作流ID',
    `run_mode`              varchar(20)   NOT NULL                         COMMENT '运行方式（ONCE/DAILY/WEEKLY/INTERVAL，后端白名单语义）',
    `timezone`              varchar(64)   NOT NULL                         COMMENT 'IANA 时区',
    `rule_json`             longtext       DEFAULT NULL                    COMMENT '结构化运行规则',
    `fixed_target_json`     longtext       DEFAULT NULL                    COMMENT '固定目标快照（原地址及设备）',
    `execution_snapshot_json` longtext     NOT NULL                        COMMENT '完整执行快照（API prompt+节点绑定+参数）',
    `params_json`           longtext       DEFAULT NULL                    COMMENT '公共参数与逐项覆盖',
    `material_refs_json`    longtext       DEFAULT NULL                    COMMENT '素材引用',
    `task_count_per_run`    int           NOT NULL DEFAULT 1              COMMENT '每次任务数量',
    `backlog_limit`         int           NOT NULL DEFAULT 1000           COMMENT '积压上限',
    `next_run_at_utc`       datetime(3)   DEFAULT NULL                     COMMENT '下一次计划触发时间（UTC）',
    `scan_cursor_utc`       datetime(3)   DEFAULT NULL                     COMMENT '补执行游标（UTC）',
    `has_unmaterialized`    bit(1)        DEFAULT b'0'                      COMMENT '是否存在未物化到期区间（存在时拒绝编辑/暂停/归档）',
    `status`                tinyint       UNSIGNED NOT NULL DEFAULT 4     COMMENT '状态（1：ACTIVE；2：BLOCKED；3：PAUSED；4：DRAFT；5：ARCHIVED）',
    `config_revision`       bigint        NOT NULL DEFAULT 0              COMMENT '计划配置版本（递增）',
    `create_user`           bigint        DEFAULT NULL                    COMMENT '创建人',
    `create_time`           datetime      NOT NULL                        COMMENT '创建时间',
    `update_user`           bigint        DEFAULT NULL                    COMMENT '修改人',
    `update_time`           datetime      DEFAULT NULL                    COMMENT '修改时间',
    `deleted`               bigint        NOT NULL DEFAULT 0              COMMENT '是否已删除（0：否；id：是）',
    PRIMARY KEY (`id`),
    INDEX `idx_comfy_schedule_user_status`(`user_id`, `status`),
    INDEX `idx_comfy_schedule_next_run`(`status`, `next_run_at_utc`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='ComfyUI 用户计划表';

